package io.github.kvtttba.droplet.core.security

import android.security.keystore.KeyGenParameterSpec
import android.security.keystore.KeyProperties
import java.nio.charset.StandardCharsets
import java.security.KeyStore
import java.util.Base64
import javax.crypto.Cipher
import javax.crypto.KeyGenerator
import javax.crypto.SecretKey
import javax.crypto.spec.GCMParameterSpec

/**
 * Sanitized exception thrown when local secret encryption/decryption fails.
 * Messages intentionally never contain plaintext credentials or raw key bytes.
 */
class SecretCipherException(
    message: String,
    cause: Throwable? = null,
) : RuntimeException(message, cause)

/**
 * Provides the AES-256 symmetric [SecretKey] used by [KeystoreSecretCipher].
 */
fun interface SecretKeyProvider {
    fun getOrCreateSecretKey(): SecretKey
}

/**
 * Production [SecretKeyProvider] backed by Android Keystore (`AES/GCM/NoPadding`, 256-bit).
 */
class AndroidKeystoreSecretKeyProvider(
    private val keyAlias: String = SecurityContract.DEFAULT_SECRET_KEY_ALIAS,
    private val providerName: String = SecurityContract.KEYSTORE_PROVIDER,
) : SecretKeyProvider {

    init {
        require(keyAlias.isNotBlank()) { "Keystore key alias must not be blank." }
    }

    private val lock = Any()

    override fun getOrCreateSecretKey(): SecretKey = synchronized(lock) {
        try {
            val keyStore = KeyStore.getInstance(providerName).apply { load(null) }
            val existing = keyStore.getKey(keyAlias, null) as? SecretKey
            if (existing != null) {
                return existing
            }
            val keyGenerator = KeyGenerator.getInstance(KeyProperties.KEY_ALGORITHM_AES, providerName)
            val spec = KeyGenParameterSpec.Builder(
                keyAlias,
                KeyProperties.PURPOSE_ENCRYPT or KeyProperties.PURPOSE_DECRYPT,
            )
                .setBlockModes(KeyProperties.BLOCK_MODE_GCM)
                .setEncryptionPaddings(KeyProperties.ENCRYPTION_PADDING_NONE)
                .setKeySize(KEY_SIZE_BITS)
                .setRandomizedEncryptionRequired(true)
                .build()
            keyGenerator.init(spec)
            keyGenerator.generateKey()
        } catch (t: Throwable) {
            throw SecretCipherException("Unable to load or generate Android Keystore AES-256 key.", t)
        }
    }

    companion object {
        const val KEY_SIZE_BITS: Int = 256
    }
}

/**
 * Local credential encryption abstraction for sensitive configuration values
 * (such as AI API Keys and WebDAV passwords). Never logs secrets.
 */
interface SecretCipher {
    fun encrypt(plaintext: String, associatedData: String = ""): String

    fun decrypt(ciphertextBase64: String, associatedData: String = ""): String
}

/**
 * AES-256-GCM cipher backed by [SecretKeyProvider] (Android Keystore in production).
 *
 * Binary payload format before Base64 encoding:
 * `[version: 1 byte (0x01)][ivLength: 1 byte][iv: ivLength bytes][ciphertext + 16-byte GCM tag]`
 */
class KeystoreSecretCipher(
    private val keyProvider: SecretKeyProvider,
) : SecretCipher {

    override fun encrypt(plaintext: String, associatedData: String): String {
        val plaintextBytes = plaintext.toByteArray(StandardCharsets.UTF_8)
        return try {
            val secretKey = keyProvider.getOrCreateSecretKey()
            val cipher = Cipher.getInstance(TRANSFORMATION)
            cipher.init(Cipher.ENCRYPT_MODE, secretKey)
            if (associatedData.isNotEmpty()) {
                cipher.updateAAD(associatedData.toByteArray(StandardCharsets.UTF_8))
            }
            val iv = cipher.iv
            if (iv == null || iv.size !in MIN_IV_BYTES..MAX_IV_BYTES) {
                throw SecretCipherException("Unexpected GCM IV length generated by crypto provider.")
            }
            val encrypted = cipher.doFinal(plaintextBytes)
            val payload = ByteArray(HEADER_BYTES + iv.size + encrypted.size)
            payload[0] = FORMAT_VERSION_V1
            payload[1] = iv.size.toByte()
            System.arraycopy(iv, 0, payload, HEADER_BYTES, iv.size)
            System.arraycopy(encrypted, 0, payload, HEADER_BYTES + iv.size, encrypted.size)
            Base64.getEncoder().encodeToString(payload)
        } catch (e: SecretCipherException) {
            throw e
        } catch (t: Throwable) {
            throw SecretCipherException("Failed to encrypt local secret.", t)
        } finally {
            plaintextBytes.fill(0)
        }
    }

    override fun decrypt(ciphertextBase64: String, associatedData: String): String {
        if (ciphertextBase64.isBlank()) {
            throw SecretCipherException("Encrypted secret payload must not be blank.")
        }
        val payload = try {
            Base64.getDecoder().decode(ciphertextBase64)
        } catch (t: IllegalArgumentException) {
            throw SecretCipherException("Encrypted secret payload is not valid Base64.", t)
        }
        if (payload.size < HEADER_BYTES + MIN_IV_BYTES + GCM_TAG_BYTES) {
            throw SecretCipherException("Encrypted secret payload is truncated.")
        }
        val version = payload[0]
        if (version != FORMAT_VERSION_V1) {
            throw SecretCipherException("Unsupported encrypted secret format version.")
        }
        val ivLength = payload[1].toInt() and 0xFF
        if (ivLength !in MIN_IV_BYTES..MAX_IV_BYTES) {
            throw SecretCipherException("Invalid GCM IV length in encrypted payload.")
        }
        val cipherOffset = HEADER_BYTES + ivLength
        val cipherLength = payload.size - cipherOffset
        if (cipherLength < GCM_TAG_BYTES) {
            throw SecretCipherException("Encrypted secret payload is missing GCM authentication tag.")
        }

        val iv = payload.copyOfRange(HEADER_BYTES, cipherOffset)
        var decryptedBytes: ByteArray? = null
        return try {
            val secretKey = keyProvider.getOrCreateSecretKey()
            val cipher = Cipher.getInstance(TRANSFORMATION)
            cipher.init(Cipher.DECRYPT_MODE, secretKey, GCMParameterSpec(GCM_TAG_LENGTH_BITS, iv))
            if (associatedData.isNotEmpty()) {
                cipher.updateAAD(associatedData.toByteArray(StandardCharsets.UTF_8))
            }
            decryptedBytes = cipher.doFinal(payload, cipherOffset, cipherLength)
            String(decryptedBytes, StandardCharsets.UTF_8)
        } catch (e: SecretCipherException) {
            throw e
        } catch (t: Throwable) {
            throw SecretCipherException("Failed to decrypt or authenticate local secret.", t)
        } finally {
            decryptedBytes?.fill(0)
        }
    }

    companion object {
        const val TRANSFORMATION: String = "AES/GCM/NoPadding"
        const val FORMAT_VERSION_V1: Byte = 1
        const val GCM_TAG_LENGTH_BITS: Int = 128
        private const val GCM_TAG_BYTES: Int = GCM_TAG_LENGTH_BITS / 8
        private const val HEADER_BYTES: Int = 2
        private const val MIN_IV_BYTES: Int = 12
        private const val MAX_IV_BYTES: Int = 16
    }
}

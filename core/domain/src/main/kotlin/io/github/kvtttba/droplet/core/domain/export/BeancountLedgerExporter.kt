package io.github.kvtttba.droplet.core.domain.export

import io.github.kvtttba.droplet.core.model.Account
import io.github.kvtttba.droplet.core.model.AccountSubType
import io.github.kvtttba.droplet.core.model.AccountType
import io.github.kvtttba.droplet.core.model.Currency
import io.github.kvtttba.droplet.core.model.Tag
import io.github.kvtttba.droplet.core.model.Transaction
import io.github.kvtttba.droplet.core.model.TransactionStatus
import java.nio.charset.StandardCharsets
import java.time.Instant
import java.time.LocalDate
import java.time.ZoneId
import java.time.format.DateTimeFormatter

/**
 * Pure Kotlin Beancount plain-text double-entry ledger exporter.
 *
 * Output structure:
 * - Standard `option "operating_currency"` header
 * - Deterministic `open` account declarations mapped onto `Assets:`, `Liabilities:`, `Equity:`,
 *   `Income:`, and `Expenses:` roots, dated no later than the earliest transaction
 * - Chronologically sorted transactions carrying date, status flag (`*` or `!`), escaped payee &
 *   narration, `#tags`, and all balanced postings (including `Equity:Trading:{CCY}` hedges for
 *   cross-currency transactions plus investment quantity/unit-price & FX rate metadata comments).
 */
internal object BeancountLedgerExporter {

    private val DATE_FORMATTER: DateTimeFormatter = DateTimeFormatter.ISO_LOCAL_DATE

    fun export(
        transactions: List<Transaction>,
        accountsById: Map<String, Account>,
        tagsById: Map<String, Tag>,
        baseCurrency: Currency,
        zoneId: ZoneId,
        generatedAtEpochMs: Long,
    ): ByteArray {
        val chronological = transactions.sortedWith(
            compareBy<Transaction>({ it.occurredAt }, { it.createdAt }, { it.id }),
        )

        val referencedAccountIds = linkedSetOf<String>()
        for (tx in chronological) {
            for (posting in tx.postings) {
                referencedAccountIds += posting.accountId
            }
        }

        val beancountNames = buildUniqueAccountNames(referencedAccountIds, accountsById)

        // Compute open date for each referenced account (strictly <= first transaction using it)
        val openDates = hashMapOf<String, LocalDate>()
        val openCurrencies = hashMapOf<String, LinkedHashSet<Currency>>()
        for (tx in chronological) {
            val txDate = Instant.ofEpochMilli(tx.occurredAt).atZone(zoneId).toLocalDate()
            for (posting in tx.postings) {
                val existingDate = openDates[posting.accountId]
                if (existingDate == null || txDate.isBefore(existingDate)) {
                    openDates[posting.accountId] = txDate
                }
                openCurrencies.getOrPut(posting.accountId) { linkedSetOf() }.add(posting.currency)
            }
        }
        val fallbackDate = Instant.ofEpochMilli(generatedAtEpochMs).atZone(zoneId).toLocalDate()
        for (accountId in referencedAccountIds) {
            val account = accountsById[accountId]
            val createdDate = account?.let {
                Instant.ofEpochMilli(it.createdAt).atZone(zoneId).toLocalDate()
            }
            val current = openDates[accountId]
            val resolved = when {
                current != null && createdDate != null && createdDate.isBefore(current) -> createdDate
                current != null -> current
                createdDate != null -> createdDate
                else -> fallbackDate
            }
            openDates[accountId] = resolved
            if (account != null) {
                openCurrencies.getOrPut(accountId) { linkedSetOf() }.add(account.currency)
            }
        }

        val sb = StringBuilder(chronological.size * 220 + 512)
        val genDateStr = DATE_FORMATTER.format(fallbackDate)
        sb.append("; Generated by Droplet Ledger on ").append(genDateStr).append('\n')
        sb.append("option \"title\" \"Droplet 记账导出\"\n")
        sb.append("option \"operating_currency\" \"").append(baseCurrency.code).append("\"\n\n")

        // 1. Account open declarations sorted by canonical Beancount account name
        val sortedAccounts = referencedAccountIds.sortedBy { beancountNames.getValue(it) }
        if (sortedAccounts.isNotEmpty()) {
            sb.append("; === Account Declarations ===\n")
            for (accountId in sortedAccounts) {
                val openDate = DATE_FORMATTER.format(openDates.getValue(accountId))
                val name = beancountNames.getValue(accountId)
                val currencies = openCurrencies[accountId].orEmpty()
                    .map { it.code }
                    .sorted()
                    .joinToString(",")
                sb.append(openDate).append(" open ").append(name)
                if (currencies.isNotEmpty()) {
                    sb.append(' ').append(currencies)
                }
                sb.append('\n')
            }
            sb.append('\n')
        }

        // 2. Transactions
        sb.append("; === Transactions ===\n")
        for (tx in chronological) {
            val txDate = DATE_FORMATTER.format(Instant.ofEpochMilli(tx.occurredAt).atZone(zoneId).toLocalDate())
            val flag = when (tx.status) {
                TransactionStatus.POSTED -> "*"
                TransactionStatus.DRAFT,
                TransactionStatus.VOID,
                -> "!"
            }
            val payee = escapeQuotedString(tx.payee?.trim().orEmpty())
            val narration = escapeQuotedString(
                tx.note?.trim()?.takeIf { it.isNotEmpty() } ?: tx.displayType.name,
            )

            sb.append(txDate).append(' ').append(flag)
            if (payee.isNotEmpty()) {
                sb.append(" \"").append(payee).append("\" \"").append(narration).append('"')
            } else {
                sb.append(" \"").append(narration).append('"')
            }

            val formattedTags = buildList {
                if (tx.status == TransactionStatus.VOID) {
                    add("#void")
                }
                for (tagId in tx.tagIds) {
                    val tagName = tagsById[tagId]?.name ?: tagId
                    val clean = sanitizeTagSegment(tagName)
                    if (clean.isNotEmpty()) {
                        add("#$clean")
                    }
                }
            }.distinct()
            for (tag in formattedTags) {
                sb.append(' ').append(tag)
            }
            sb.append('\n')
            sb.append("  droplet-id: \"").append(escapeQuotedString(tx.id)).append("\"\n")
            sb.append("  droplet-type: \"").append(tx.displayType.name).append("\"\n")

            for (posting in tx.postings) {
                val accountName = beancountNames.getValue(posting.accountId)
                val amountStr = ExportDecimalFormatter.formatMoney(posting.money)
                sb.append("  ").append(accountName).append("  ")
                sb.append(amountStr).append(' ').append(posting.currency.code)

                val comments = buildList {
                    if (posting.currency != posting.baseCurrency) {
                        add("rate=${posting.exchangeRateSnapshot.rateDecimal}")
                        add("base=${ExportDecimalFormatter.formatMoney(posting.baseMoney)} ${posting.baseCurrency.code}")
                    }
                    if (posting.quantity != null) {
                        add("qty=${posting.quantity!!.canonical}")
                    }
                    if (posting.unitPrice != null) {
                        add("price=${posting.unitPrice!!.canonical} ${posting.currency.code}")
                    }
                    if (posting.isSystemBalancing) {
                        add("trading-hedge")
                    }
                }
                if (comments.isNotEmpty()) {
                    sb.append("  ; ").append(comments.joinToString(" "))
                }
                sb.append('\n')
            }
            sb.append('\n')
        }

        return sb.toString().toByteArray(StandardCharsets.UTF_8)
    }

    private fun buildUniqueAccountNames(
        accountIds: Set<String>,
        accountsById: Map<String, Account>,
    ): Map<String, String> {
        val result = linkedMapOf<String, String>()
        val used = hashSetOf<String>()

        for (accountId in accountIds.sorted()) {
            val account = accountsById[accountId]
            val candidate = if (account != null) {
                mapAccountToBeancountName(account, accountsById)
            } else {
                "Assets:Unknown:${sanitizeSegment(accountId)}"
            }
            var finalName = candidate
            var suffix = 2
            while (!used.add(finalName)) {
                finalName = "$candidate-$suffix"
                suffix++
            }
            result[accountId] = finalName
        }
        return result
    }

    internal fun mapAccountToBeancountName(
        account: Account,
        accountsById: Map<String, Account>,
    ): String {
        val root = when (account.type) {
            AccountType.ASSET -> "Assets"
            AccountType.LIABILITY -> "Liabilities"
            AccountType.EQUITY -> "Equity"
            AccountType.INCOME -> "Income"
            AccountType.EXPENSE -> "Expenses"
        }

        if (account.subType == AccountSubType.TRADING) {
            return "Equity:Trading:${account.currency.code}"
        }
        if (account.subType == AccountSubType.OPENING) {
            return "Equity:OpeningBalances:${account.currency.code}"
        }

        val segments = mutableListOf<String>()
        segments += root

        val parent = account.parentId?.let { accountsById[it] }
        if (account.subType == AccountSubType.CATEGORY) {
            if (parent != null) {
                segments += sanitizeSegment(parent.name)
            }
            segments += sanitizeSegment(account.name)
        } else {
            val subTypeGroup = when (account.subType) {
                AccountSubType.CASH -> "Cash"
                AccountSubType.DEBIT_CARD -> "DebitCard"
                AccountSubType.CREDIT_CARD -> "CreditCard"
                AccountSubType.STORED_VALUE -> "StoredValue"
                AccountSubType.INVEST_CASH -> "InvestCash"
                AccountSubType.INVEST_HOLDING -> "InvestHolding"
                AccountSubType.LOAN -> "Loan"
                AccountSubType.RECEIVABLE -> "Receivable"
                AccountSubType.PAYABLE -> "Payable"
                AccountSubType.REIMBURSEMENT -> "Reimbursement"
                AccountSubType.CATEGORY,
                AccountSubType.TRADING,
                AccountSubType.OPENING,
                -> "Other"
            }
            segments += subTypeGroup
            segments += sanitizeSegment(account.name)
        }

        return segments.joinToString(":")
    }

    private fun sanitizeSegment(raw: String): String {
        val cleaned = raw.trim()
            .replace(Regex("[\\s:/\\\\\"'`@#\$%^&*()+=\\[\\]{}|;,.<>?!~]+"), "-")
            .trim('-')
        val nonEmpty = cleaned.ifEmpty { "Account" }
        val first = nonEmpty.first()
        return when {
            first.isUpperCase() -> nonEmpty
            first in 'a'..'z' -> first.uppercaseChar() + nonEmpty.substring(1)
            else -> "A$nonEmpty"
        }
    }

    private fun sanitizeTagSegment(raw: String): String = raw.trim()
        .replace(Regex("[\\s:/\\\\\"'`@#\$%^&*()+=\\[\\]{}|;,<>?!~]+"), "-")
        .trim('-')

    private fun escapeQuotedString(raw: String): String =
        raw.replace("\\", "\\\\")
            .replace("\"", "\\\"")
            .replace("\r", " ")
            .replace("\n", " ")
}
